"""Embed an unchanged yourself.py from a clean local upstream commit; no network."""
import argparse
import ast
import hashlib
from pathlib import Path
import subprocess

START = '# BEGIN BUNDLED YOURSELF (generated by scripts/update_yourself.py)'
END = '# END BUNDLED YOURSELF'


def update(upstream, target):
    upstream, target = Path(upstream).resolve(), Path(target).resolve()
    commit = subprocess.check_output(['git', '-C', str(upstream), 'rev-parse', 'HEAD'], text=True).strip()
    contents = {}
    for name in ('yourself.py', 'LICENSE'):
        pinned = subprocess.check_output(['git', '-C', str(upstream), 'show', f'{commit}:{name}'])
        if (upstream / name).read_bytes() != pinned:
            raise ValueError(f'{name} differs from the pinned upstream commit')
        contents[name] = pinned.decode('utf-8')
    source = contents['yourself.py']
    tree = ast.parse(source)
    if not any(isinstance(n, ast.FunctionDef) and n.name == 'main' for n in tree.body):
        raise ValueError('upstream must expose main(argv)')
    compile(source, 'yourself.py', 'exec')
    digest = hashlib.sha256(source.encode()).hexdigest()
    def literal(text):
        return "r'''" + text + "'''" if "'''" not in text and not text.endswith('\\') else repr(text)
    block = '\n'.join([START,
        '# Upstream: https://github.com/myon-bioinformatics/yourself',
        f'_YOURSELF_COMMIT = {commit!r}', f'_YOURSELF_SHA256 = {digest!r}',
        '_YOURSELF_LICENSE = ' + literal(contents['LICENSE']),
        '_YOURSELF_SOURCE = ' + literal(source), END])
    original = target.read_text()
    if START in original:
        begin, finish = original.index(START), original.index(END) + len(END)
        result = original[:begin] + block + original[finish:]
    else:
        marker = 'if __name__ == "__main__":'
        begin = 0 if original.startswith(marker) else original.find('\n' + marker) + 1
        if begin == 0 and not original.startswith(marker):
            raise ValueError('target has no CLI entry point')
        result = original[:begin] + block + '\n\n' + original[begin:]
    compile(result, str(target), 'exec')
    target.write_text(result)
    return commit, digest


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('upstream', help='local clone of myon-bioinformatics/yourself')
    parser.add_argument('--target', type=Path, default=Path(__file__).resolve().parents[1] / 'olnm.py')
    args = parser.parse_args()
    commit, digest = update(args.upstream, args.target)
    print(f'yourself {commit} sha256={digest}')
